import { test, expect } from '@playwright/test'
import credits from '../../smart-community-frontend/src/assets/marketplace-image-credits.json'

test('all fifteen seeded product images are local, available and licensed', async ({ request }) => {
  const login = await (await request.post('/api/v1/auth/login', { data: { username: 'admin', password: process.env.COMMUNITY_TEST_PASSWORD || 'admin123' } })).json()
  const result = await (await request.get('/api/v1/secondhand/list?pageSize=100', { headers: { Authorization: `Bearer ${login.data.token}` } })).json()
  expect(result.code).toBe(200)
  expect(credits).toHaveLength(15)
  expect(new Set(credits.map(credit => credit.image)).size).toBe(15)
  for (const credit of credits) {
    const item = result.data.records.find((row: any) => row.itemNo === credit.itemNo)
    expect(item, credit.itemNo).toBeTruthy()
    expect(JSON.parse(item.images), item.title).toEqual([credit.image])
    expect(credit.image).toMatch(/^\/uploads\/community\/[a-f\d-]+\.jpg$/)
    expect(credit.author).toBeTruthy(); expect(credit.source).toMatch(/^https:\/\/commons.wikimedia.org\//)
    expect(credit.license).toMatch(/^(CC BY|CC0|Public domain)/)
    const image = await request.get(credit.image)
    expect(image.status(), item.title).toBe(200)
    expect(image.headers()['content-type']).toContain('image/jpeg')
    const bytes = await image.body()
    expect(bytes.length).toBeGreaterThan(2000)
    expect(bytes.subarray(0, 2).toString('hex')).toBe('ffd8')
  }
})

