  await page.locator('.item-image img').evaluateAll(images => images.forEach(image => (image as HTMLImageElement).loading = 'eager'))
  await expect.poll(() => page.locator('.item-image img').evaluateAll(images => images.every(image => (image as HTMLImageElement).complete && (image as HTMLImageElement).naturalWidth === 960))).toBe(true)
