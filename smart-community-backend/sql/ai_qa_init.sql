-- 1. 问答记录表
CREATE TABLE IF NOT EXISTS `sys_qa_log` (
    `id`          BIGINT       NOT NULL AUTO_INCREMENT COMMENT '主键ID',
    `question`    TEXT         NOT NULL COMMENT '用户提问',
    `answer`      TEXT         NOT NULL COMMENT 'AI回答',
    `sources`     JSON         NULL     COMMENT '检索来源ID列表',
    `user_id`     BIGINT       NULL     COMMENT '提问用户ID',
    `user_name`   VARCHAR(50)  NULL     COMMENT '提问用户名',
    `create_by`   BIGINT       NULL     COMMENT '创建人',
    `create_time` DATETIME     DEFAULT CURRENT_TIMESTAMP COMMENT '创建时间',
    `update_by`   BIGINT       NULL     COMMENT '更新人',
    `update_time` DATETIME     DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP COMMENT '更新时间',
    `deleted`     TINYINT(1)   DEFAULT 0 COMMENT '逻辑删除',
    `remark`      VARCHAR(500) NULL     COMMENT '备注',
    PRIMARY KEY (`id`),
    KEY `idx_user_id` (`user_id`),
    KEY `idx_create_time` (`create_time`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='AI智能问答记录';

-- 2. 知识库文档表
CREATE TABLE IF NOT EXISTS `sys_knowledge_doc` (
    `id`           BIGINT       NOT NULL AUTO_INCREMENT COMMENT '主键ID',
    `title`        VARCHAR(200) NOT NULL COMMENT '文档标题',
    `content`      MEDIUMTEXT   NOT NULL COMMENT '文档内容',
    `category`     VARCHAR(50)  NULL     COMMENT '分类: property=物业管理, guard=安防管理, fee=费用管理, life=生活服务, social=社区互动, general=综合信息',
    `embedding_id` VARCHAR(100) NULL     COMMENT '向量存储中的文档ID',
    `status`       TINYINT(1)   DEFAULT 1 COMMENT '状态: 0=禁用, 1=启用',
    `create_by`    BIGINT       NULL     COMMENT '创建人',
    `create_time`  DATETIME     DEFAULT CURRENT_TIMESTAMP COMMENT '创建时间',
    `update_by`    BIGINT       NULL     COMMENT '更新人',
    `update_time`  DATETIME     DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP COMMENT '更新时间',
    `deleted`      TINYINT(1)   DEFAULT 0 COMMENT '逻辑删除',
    `remark`       VARCHAR(500) NULL     COMMENT '备注',
    PRIMARY KEY (`id`),
    KEY `idx_category` (`category`),
    KEY `idx_status` (`status`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='AI知识库文档';

